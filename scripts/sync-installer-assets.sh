#!/usr/bin/env bash
# Synchronise the deploy assets embedded in installer/install.sh with their
# canonical sources under deploy/.
#
# The installer must work when piped to `sh` (no neighbouring files available),
# so systemd units and the default rast.toml template are embedded as heredocs.
# This script is the single source of truth mapper:
#
#   deploy/rast.toml.example   -> write_config_template()   in installer/install.sh
#   deploy/rast.service        -> write_unit_rast_service()  in installer/install.sh
#   deploy/rast-worker.service -> write_unit_rast_worker()   in installer/install.sh
#
# Usage:
#   scripts/sync-installer-assets.sh           # rewrite the embedded blocks
#   scripts/sync-installer-assets.sh --check   # fail if the file is out of date
#
# CI runs --check, so editing deploy/* without re-running this script fails the
# build instead of shipping a divergent installer.

set -euo pipefail

ROOT=$(cd -- "$(dirname -- "$0")/.." && pwd)
INSTALLER="$ROOT/installer/install.sh"

# "source file|wrapper function|heredoc delimiter"
SPECS=(
    "deploy/rast.toml.example|write_config_template|RAST_EMBED_CONFIG_TEMPLATE"
    "deploy/rast.service|write_unit_rast_service|RAST_EMBED_RAST_SERVICE"
    "deploy/rast-worker.service|write_unit_rast_worker|RAST_EMBED_RAST_WORKER"
)

MODE="write"
case "${1:-}" in
    --check) MODE="check" ;;
    -h | --help)
        sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
        exit 0
        ;;
    "") ;;
    *)
        echo "sync-installer-assets: unknown argument: $1 (try --help)" >&2
        exit 2
        ;;
esac

[[ -f "$INSTALLER" ]] || {
    echo "sync-installer-assets: missing $INSTALLER" >&2
    exit 1
}

work=$(mktemp -d "${TMPDIR:-/tmp}/rast-sync.XXXXXX")
cleanup() { rm -rf -- "$work"; }
trap cleanup EXIT

cp -- "$INSTALLER" "$work/install.sh"
block="$work/block"

for spec in "${SPECS[@]}"; do
    IFS='|' read -r src fn tag <<<"$spec"
    src_abs="$ROOT/$src"
    [[ -f "$src_abs" ]] || {
        echo "sync-installer-assets: missing source $src" >&2
        exit 1
    }

    begin="# >>> BEGIN embedded $src"
    end="# <<< END embedded $src"
    # The begin marker is matched by prefix so that older generated blocks
    # (which carried a suffix) are migrated cleanly.
    begin_count=$(awk -v b="$begin" 'index($0, b) == 1 { c++ } END { print c + 0 }' "$work/install.sh")
    end_count=$(grep -cFx -- "$end" "$work/install.sh" || true)
    if [[ "$begin_count" != "1" || "$end_count" != "1" ]]; then
        echo "sync-installer-assets: $INSTALLER must contain exactly one '$begin' and '$end' (found $begin_count/$end_count)" >&2
        exit 1
    fi

    {
        printf '# >>> BEGIN embedded %s\n' "$src"
        printf '# Generated by scripts/sync-installer-assets.sh from %s — do not edit.\n' "$src"
        printf '%s() {\n' "$fn"
        # shellcheck disable=SC2016 # "$1" must reach the generated script literally.
        printf '    cat > "$1" <<%s\n' "'$tag'"
        cat -- "$src_abs"
        # The source file always ends with a newline; guard anyway so that the
        # delimiter is never glued to the last content line.
        if [[ -n "$(tail -c 1 -- "$src_abs")" ]]; then
            printf '\n'
        fi
        printf '%s\n' "$tag"
        printf '}\n'
        printf '# <<< END embedded %s\n' "$src"
    } >"$block"

    awk -v begin="$begin" -v end="$end" -v blockfile="$block" '
        index($0, begin) == 1 {
            while ((getline line < blockfile) > 0) print line
            close(blockfile)
            skipping = 1
            next
        }
        skipping && index($0, end) == 1 { skipping = 0; next }
        skipping { next }
        { print }
    ' "$work/install.sh" >"$work/next.sh"
    mv -- "$work/next.sh" "$work/install.sh"
done

if cmp -s -- "$work/install.sh" "$INSTALLER"; then
    echo "sync-installer-assets: installer embeds are up to date"
    exit 0
fi

if [[ "$MODE" == "check" ]]; then
    echo "sync-installer-assets: ERROR: installer/install.sh is out of date." >&2
    echo "Run scripts/sync-installer-assets.sh and commit the result." >&2
    diff -u -- "$INSTALLER" "$work/install.sh" || true
    exit 1
fi

# Preserve the existing file mode/owner: `cp` over an existing destination
# updates its contents without replacing the inode.
cp -- "$work/install.sh" "$INSTALLER"
chmod 0755 "$INSTALLER"
echo "sync-installer-assets: updated $INSTALLER"
