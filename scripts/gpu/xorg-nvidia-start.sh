#!/bin/bash
# xorg-nvidia-start.sh — start (or check) a headless NVIDIA Xorg display.
#
#   sudo scripts/gpu/xorg-nvidia-start.sh 110                 # 1920x1080x24, background
#   sudo scripts/gpu/xorg-nvidia-start.sh 110 2560x1440x24    # custom size
#   sudo scripts/gpu/xorg-nvidia-start.sh 110 --foreground    # run in foreground
#   scripts/gpu/xorg-nvidia-start.sh 110 --check              # verify a running one
#
# Requires: xserver-xorg-core + xserver-xorg-video-nvidia-595 + libnvidia-gl-595
# (libnvidia-gl-595 ships the "glxserver_nvidia" GLX server module; without it
# Xorg falls back to swrast/llvmpipe and glxinfo reports llvmpipe).
#
# Prints the glxinfo renderer and exits non-zero unless the NVIDIA renderer is
# active. The display is standalone: kill it with `sudo pkill -x Xorg` or
# `sudo kill $(cat /run/rast-gpu/Xorg-<n>.pid)`.
set -u

die() { echo "error: $*" >&2; exit 1; }
[ $# -ge 1 ] || die "usage: $0 <display-number> [WxHxD] [--foreground|--check]"

display_num="$1"; shift
[ -n "$display_num" ] || die "empty display number"
[[ "$display_num" =~ ^[0-9]+$ ]] || die "display must be a number, e.g. 110"
display=":$display_num"

geometry="1920x1080x24"
mode="background"
for a in "$@"; do
    case "$a" in
        --foreground) mode="foreground" ;;
        --check) mode="check" ;;
        --*) die "unknown option $a" ;;
        *) geometry="$a" ;;
    esac
done
[[ "$geometry" =~ ^([0-9]+)x([0-9]+)x([0-9]+)$ ]] || die "geometry must be WxHxD"
width="${BASH_REMATCH[1]}"; height="${BASH_REMATCH[2]}"; depth="${BASH_REMATCH[3]}"

rundir="/run/rast-gpu"
logdir="$rundir/logs"
confdir="$rundir/xorg"
conf="$confdir/xorg-nvidia-headless-$display_num.conf"
xlog="$logdir/Xorg-$display_num.log"

check() {
    local renderer
    renderer="$(DISPLAY="$display" glxinfo -B 2>/dev/null | sed -n 's/^OpenGL renderer string: //p' | head -1)"
    if [ -z "$renderer" ]; then
        echo "glxinfo could not connect to $display"
        return 1
    fi
    echo "OpenGL renderer on $display: $renderer"
    case "$renderer" in
        *NVIDIA*) return 0 ;;
        *) echo "NOT hardware accelerated (expected an NVIDIA renderer)"; return 1 ;;
    esac
}

if [ "$mode" = "check" ]; then
    check || exit 1
    exit 0
fi

[ "$(id -u)" = 0 ] || die "Xorg needs root for VT setup (parse_vt_settings: Cannot open /dev/tty0): re-run with sudo"
[ -x /usr/lib/xorg/Xorg ] || die "/usr/lib/xorg/Xorg missing: apt-get install xserver-xorg-core"
[ -f /usr/lib/x86_64-linux-gnu/nvidia/xorg/nvidia_drv.so ] ||
    die "nvidia_drv.so missing: apt-get install xserver-xorg-video-nvidia-595"
[ -f /usr/lib/x86_64-linux-gnu/nvidia/xorg/libglxserver_nvidia.so ] ||
    die "libglxserver_nvidia.so missing: apt-get install libnvidia-gl-595"

command -v nvidia-smi >/dev/null 2>&1 || die "nvidia-smi missing"
nvidia-smi -L >/dev/null 2>&1 || die "the NVIDIA driver cannot see a GPU"

[ -e "/tmp/.X11-unix/X$display_num" ] || [ -e "/tmp/.X$display_num-lock" ] &&
    die "display $display is already in use"

mkdir -p "$confdir" "$logdir" || die "cannot create $rundir"

cat >"$conf" <<EOF
# Generated by RAST scripts/gpu/xorg-nvidia-start.sh
Section "ServerLayout"
    Identifier     "rast-headless-$display_num"
    Screen      0  "rastscreen"
EndSection

Section "Files"
    ModulePath     "/usr/lib/x86_64-linux-gnu/nvidia/xorg"
    ModulePath     "/usr/lib/xorg/modules"
EndSection

Section "ServerFlags"
    Option         "AutoAddDevices"    "false"
    Option         "AutoEnableDevices" "false"
    Option         "DontZap"           "true"
EndSection

Section "Monitor"
    Identifier     "rastmonitor"
    HorizSync       28.0 - 80.0
    VertRefresh     48.0 - 75.0
    Option         "DPMS" "false"
EndSection

Section "Device"
    Identifier     "rastgpu"
    Driver         "nvidia"
    BusID          "PCI:1:0:0"
    Option         "AllowEmptyInitialConfiguration" "true"
    Option         "UseDisplayDevice" "none"
    Option         "ModeValidation" "NoEdidModes,NoMaxPClkCheck,NoVertRefreshCheck,NoHorizSyncCheck,AllowNonEdidModes"
    Option         "HardDPMS" "false"
    Option         "Interactive" "false"
EndSection

Section "Screen"
    Identifier     "rastscreen"
    Device         "rastgpu"
    Monitor        "rastmonitor"
    DefaultDepth   $depth
    Option         "AllowEmptyInitialConfiguration" "true"
    SubSection     "Display"
        Depth       $depth
        Virtual     $width $height
    EndSubSection
EndSection
EOF

echo "config: $conf"
echo "log:    $xlog"

start_args=("$display" -config "$conf" -logfile "$xlog" -noreset -nolisten tcp -dpi 96)
if [ "$mode" = "foreground" ]; then
    echo "starting Xorg in the foreground on $display (${width}x${height}x${depth})"
    exec /usr/lib/xorg/Xorg "${start_args[@]}"
fi

# Detach without a controlling terminal so the shell can exit cleanly.
setsid /usr/lib/xorg/Xorg "${start_args[@]}" </dev/null >/dev/null 2>&1 &
pid=$!
echo "$pid" >"$rundir/Xorg-$display_num.pid"
echo "Xorg pid $pid on $display (${width}x${height}x${depth})"

# Wait for the display socket, then verify the GLX renderer.
for _ in $(seq 1 50); do
    [ -e "/tmp/.X11-unix/X$display_num" ] || [ -e "/tmp/.X$display_num-lock" ] && break
    sleep 0.2
done
sleep 0.5
if check; then
    exit 0
fi
echo "--- last lines of $xlog ---" >&2
tail -25 "$xlog" >&2 || true
exit 1
