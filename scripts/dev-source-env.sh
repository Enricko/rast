#!/usr/bin/env bash
# Source this file to run RAST from a source checkout without touching
# /etc/rast or /var/lib/rast:
#
#   source scripts/dev-source-env.sh
#   cargo run -- serve
#
# It exports RAST_* variables pointing at git-ignored directories under target/
# (so nothing pollutes the repository), creates them if needed, and prints the
# commands for the first-run administrator.
#
# Executing the script (instead of sourcing it) only prints instructions.

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
    cat <<'DEV_USAGE'
scripts/dev-source-env.sh must be sourced, not executed:

  source scripts/dev-source-env.sh
  cargo run -- serve

Then open http://127.0.0.1:8720 and create the first administrator:

  cargo run -- user create-admin admin --password-stdin

DEV_USAGE
    exit 0
fi

_rast_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)

export RAST_DATA_DIR="${RAST_DATA_DIR:-$_rast_root/target/dev-data}"
export RAST_STORAGE_DIR="${RAST_STORAGE_DIR:-$_rast_root/target/dev-storage}"
export RAST_CONFIG="${RAST_CONFIG:-$RAST_DATA_DIR/rast.toml}"
export RAST_BIND="${RAST_BIND:-127.0.0.1:8720}"
export RAST_PUBLIC_URL="${RAST_PUBLIC_URL:-http://127.0.0.1:8720}"
export RAST_LOG_LEVEL="${RAST_LOG_LEVEL:-debug}"
export RAST_TRUSTED_PROXIES="${RAST_TRUSTED_PROXIES:-127.0.0.1/32}"
export RAST_SETUP_TOKEN_REQUIRED="${RAST_SETUP_TOKEN_REQUIRED:-false}"
export RUST_LOG="${RUST_LOG:-rast=debug,tower_http=info}"

mkdir -p -- "$RAST_DATA_DIR" \
    "$RAST_STORAGE_DIR/homes" "$RAST_STORAGE_DIR/shared" "$RAST_STORAGE_DIR/.trash"
if [[ ! -f "$RAST_CONFIG" ]]; then
    cat >"$RAST_CONFIG" <<'DEV_CONFIG'
# Development configuration generated by scripts/dev-source-env.sh.
# Every key is optional; see deploy/rast.toml.example for the full reference.
bind = "127.0.0.1:8720"
public_url = "http://127.0.0.1:8720"
trusted_proxies = ["127.0.0.1/32", "::1/128"]
log_level = "debug"
docker_enabled = false
DEV_CONFIG
fi

cat <<DEV_INFO

RAST development environment exported:
  RAST_CONFIG       = $RAST_CONFIG
  RAST_DATA_DIR     = $RAST_DATA_DIR
  RAST_STORAGE_DIR  = $RAST_STORAGE_DIR
  RAST_BIND         = $RAST_BIND
  RAST_PUBLIC_URL   = $RAST_PUBLIC_URL

Run the server:          cargo run -- serve
Create an admin:         cargo run -- user create-admin admin --password-stdin
Show status / diagnose:  cargo run -- status ; cargo run -- doctor
Reset the dev database:  rm -rf "$RAST_DATA_DIR" "$RAST_STORAGE_DIR"

Frontend (build once):   (cd frontend && npm ci && npm run build)
DEV_INFO
